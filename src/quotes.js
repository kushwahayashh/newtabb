const lastQuoteKey = 'newtab-last-quote'

export function chooseQuote() {
  let previous
  try { previous = localStorage.getItem(lastQuoteKey) } catch { /* Storage is optional. */ }
  const candidates = quotes.filter((quote) => quote.text !== previous)
  return candidates[Math.floor(Math.random() * candidates.length)]
}

export function rememberQuote(quote) {
  try { localStorage.setItem(lastQuoteKey, quote.text) } catch { /* Storage is optional. */ }
}
